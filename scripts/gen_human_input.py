#!/usr/bin/env python3
"""Generate the human-input parameter files of the three clients.

    scripts/gen_human_input.py            write the files
    scripts/gen_human_input.py --check    exit 1 if a file is missing or stale (CI)

Input: settings/human_input.json (written by scripts/calibrate_human_input.py).
Output, never edited by hand:
    client/go/rodclient/human_params.go
    client/python/camoucrome/human_params.py
    client/node/human_params.js
All three carry the same numbers. Durations are milliseconds in Python and Node,
time.Duration (rounded to a microsecond) in Go.
"""
import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = "settings/human_input.json"
GO = "client/go/rodclient/human_params.go"
PY = "client/python/camoucrome/human_params.py"
JS = "client/node/human_params.js"
FLOORS = "client/go/rodclient/cmd/camoucrome-smoke/calibrated_floors.go"

# (json key, name base). Every lognormal group has median_ms, sigma, min_ms, max_ms.
DISTS = [
    ("dwell", "dwell"), ("flight", "flight"), ("pause", "pause"),
    ("shift_lead", "shiftLead"), ("shift_release", "shiftRelease"),
    ("settle", "settle"), ("click_hold", "clickHold"), ("tremor", "tremor"),
    ("rollover", "rolloverOverlap"), ("typos_notice", "typoNotice"),
    ("backspace_dwell", "backspaceDwell"), ("backspace_flight", "backspaceFlight"),
    ("typos_retype", "typoRetype"),
]
# (json key, field, name, kind) for single numbers; kind is float or int.
SCALARS = [
    ("flight_after_punct", "factor", "flightAfterPunct", float),
    ("flight_before_shift", "factor", "flightBeforeShift", float),
    ("pause", "chance", "pauseChance", float),
    ("tremor", "px", "tremorPx", float),
    ("tremor", "sigma_px", "tremorSigmaPx", float),
    ("click_point", "spread", "clickSpread", float),
    ("click_point", "inner", "clickInner", float),
    ("click_point", "min_box", "clickMinBox", float),
    ("rollover", "chance", "rolloverChance", float),
    ("rollover_max_down", "keys", "rolloverMaxDown", int),
    ("typos", "rate", "typoRate", float),
]
PARTS = [("median_ms", "Median", True), ("sigma", "Sigma", False),
         ("min_ms", "Min", True), ("max_ms", "Max", True)]


def snake(camel):
    return re.sub(r"([A-Z])", r"_\1", camel).upper()


def num(v):
    """A number the way every language reads it back exactly."""
    return repr(float(v)) if not float(v).is_integer() else str(int(v)) + ".0"


def js_num(v):
    return str(int(v)) if float(v).is_integer() else repr(float(v))


def entries(doc):
    """[(comment, [(name, value, is_duration, kind)...])] in output order."""
    out = []
    for key, base in DISTS:
        d = doc[key]
        items = [(base + suffix, d[f], dur, float) for f, suffix, dur in PARTS]
        out.append((f"{key}: {src(d)}", items))
    for key, field, name, kind in SCALARS:
        d = doc[key]
        out.append((f"{key}.{field}: {src(d)}", [(name, d[field], False, kind)]))
    return out


def src(d):
    n = f", n={d['n']}" if "n" in d else ""
    return f"{d['source']}{n}, {d.get('date')}"


def header(doc, comment):
    refs = "; ".join(f"{k}: {v['dataset']} ({v['licence']}) {v['url']}".rstrip()
                     for k, v in doc["refs"].items())
    return [f"{comment} Generated by scripts/gen_human_input.py from {SRC}; DO NOT EDIT.",
            f"{comment} Sources: {refs}",
            f"{comment} `scripts/gen_human_input.py --check` fails while this file is stale."]


def go_text(doc):
    L = header(doc, "//")
    L[0] = L[0].replace("// Generated", "// Code generated", 1)
    L += ["", "package rodclient", "", 'import "time"', ""]
    for comment, items in entries(doc):
        L.append(f"// {comment}")
        for name, v, dur, kind in items:
            if dur:
                L.append(f"const {name} = {round(v * 1000)} * time.Microsecond")
            else:
                L.append(f"const {name} = {int(v) if kind is int else num(v)}")
        L.append("")
    probs = ", ".join(num(p) for p in doc["typos"]["run_len_probs"])
    L += ["// typos.run_len_probs: probability of 1, 2, 3+ characters typed before a typo is noticed",
          f"var typoRunLenProbs = [...]float64{{{probs}}}", ""]
    pairs = doc["digraph"].get("pairs", {})
    L.append(f"// digraph: {src(doc['digraph'])}; median keyDown-to-keyDown of frequent letter pairs")
    # Filled in init(): gofmt column-aligns map literals, and an unaligned
    # literal would make this file differ from `gofmt` output.
    L.append("var digraphFlight = map[string]time.Duration{}")
    L.append("")
    L.append("func init() {")
    for k, v in pairs.items():
        L.append(f'\tdigraphFlight["{k}"] = {round(v["median_ms"] * 1000)} * time.Microsecond')
    L.append("}")
    return "\n".join(L) + "\n"


def py_text(doc):
    L = [f'"""{header(doc, "")[0].strip()}', *[h.strip() for h in header(doc, "")[1:]], '"""', ""]
    for comment, items in entries(doc):
        L.append(f"# {comment}")
        for name, v, dur, kind in items:
            val = str(int(v)) if kind is int else num(v)
            L.append(f"{snake(name)}{'_MS' if dur else ''} = {val}")
        L.append("")
    L.append("# typos.run_len_probs: probability of 1, 2, 3+ characters typed before a typo is noticed")
    L.append(f"TYPO_RUN_LEN_PROBS = [{', '.join(num(p) for p in doc['typos']['run_len_probs'])}]")
    L.append("")
    L.append(f"# digraph: {src(doc['digraph'])}; median keyDown-to-keyDown of frequent letter pairs")
    L.append("DIGRAPH_FLIGHT_MS = {")
    for k, v in doc["digraph"].get("pairs", {}).items():
        L.append(f'    "{k}": {num(v["median_ms"])},')
    L.append("}")
    return "\n".join(L) + "\n"


def js_text(doc):
    L = header(doc, "//")
    L += ["", "'use strict';", ""]
    names = []
    for comment, items in entries(doc):
        L.append(f"// {comment}")
        for name, v, dur, kind in items:
            n = name + ("Ms" if dur else "")
            L.append(f"const {n} = {js_num(v)};")
            names.append(n)
        L.append("")
    probs = ", ".join(js_num(p) for p in doc["typos"]["run_len_probs"])
    L += ["// typos.run_len_probs: probability of 1, 2, 3+ characters typed before a typo is noticed",
          f"const typoRunLenProbs = [{probs}];", ""]
    L.append(f"// digraph: {src(doc['digraph'])}; median keyDown-to-keyDown of frequent letter pairs")
    L.append("const digraphFlightMs = {")
    for k, v in doc["digraph"].get("pairs", {}).items():
        L.append(f'  "{k}": {js_num(v["median_ms"])},')
    L.append("};")
    L.append("")
    L.append("module.exports = {")
    for n in names + ["typoRunLenProbs", "digraphFlightMs"]:
        L.append(f"  {n},")
    L.append("};")
    return "\n".join(L) + "\n"


def floors_text(doc):
    """The smallest values rodclient can draw, for camoucrome-smoke's floors (a
    separate package that cannot see rodclient's unexported constants)."""
    L = header(doc, "//")
    L[0] = L[0].replace("// Generated", "// Code generated", 1)
    L += ["", "package main", "", "const ("]
    L.append(f"\tcalibDwellMinMs = {num(doc['dwell']['min_ms'])} // dwell.min_ms")
    L.append(f"\tcalibHoldMinMs  = {num(doc['click_hold']['min_ms'])} // click_hold.min_ms")
    L.append(f"\tcalibLeadMinMs  = {num(doc['shift_lead']['min_ms'])} // shift_lead.min_ms")
    L.append(")")
    return "\n".join(L) + "\n"


def render(doc):
    return {GO: go_text(doc), PY: py_text(doc), JS: js_text(doc), FLOORS: floors_text(doc)}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", type=pathlib.Path, default=ROOT)
    a = ap.parse_args(argv)
    doc = json.loads((a.root / SRC).read_text())
    bad = 0
    for rel, text in render(doc).items():
        path = a.root / rel
        if a.check:
            if not path.exists() or path.read_text() != text:
                print(f"{rel} is stale or missing: run scripts/gen_human_input.py", file=sys.stderr)
                bad = 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {rel}")
    return bad


if __name__ == "__main__":
    sys.exit(main())
