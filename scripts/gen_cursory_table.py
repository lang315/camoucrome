#!/usr/bin/env python3
"""Generates additions/camoucfg_lgpl/cursory_data.{h,cc} from the pinned
cursory 2.1.0 recording database (LGPL-3.0-or-later; see ../NOTICE).

    scripts/gen_cursory_table.py           rewrite the generated files
    scripts/gen_cursory_table.py --check   exit 1 if stale or the snapshot hash moved
"""
import argparse, gzip, hashlib, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LGPL = os.path.join(ROOT, "additions", "camoucfg_lgpl")
SNAPSHOT = os.path.join(LGPL, "data", "trajectories.json.gz")
PINNED_SHA256 = "1bf3af168719a580e2c5d6fb439f894f9bfff72fc90147149cc531dee80b6203"

def load(path):
    with gzip.open(path, "rt", encoding="utf-8") as f:
        return json.load(f)

def _check_range(v, lo, hi, what):
    if not lo <= v <= hi:
        raise ValueError(f"{what} {v} outside [{lo}, {hi}]")

def render(recs):
    xs, ys, ts, rows = [], [], [], []
    for i, r in enumerate(recs):
        pts, tm = r["points"], r["timing"]
        if len(pts) != len(tm) or len(pts) < 2:
            raise ValueError(f"recording {i}: points/timing mismatch or < 2 points")
        _check_range(len(pts), 2, 65535, "point count")
        t0 = tm[0]
        prev = -1
        for (x, y), t in zip(pts, tm):
            _check_range(x, -32768, 32767, "x"); _check_range(y, -32768, 32767, "y")
            rel = int(round(t - t0))
            _check_range(rel, 0, 65535, "timing")
            if rel < prev:
                raise ValueError(f"recording {i}: timing not monotonic")
            prev = rel
            xs.append(int(x)); ys.append(int(y)); ts.append(rel)
        rows.append((len(xs) - len(pts), len(pts), float(r["length"])))
    def arr(name, ty, vals):
        body = ", ".join(map(str, vals))
        return f"const {ty} {name}[] = {{{body}}};\n"
    rec = ", ".join(f"{{{a}, {b}, {l:.6f}f}}" for a, b, l in rows)
    src = (
        HEADER_COMMENT + '#include "components/camoucfg_lgpl/cursory_data.h"\n\n'
        "namespace cursory::data {\n"
        f"const Recording kRecordings[] = {{{rec}}};\n"
        f"const size_t kRecordingCount = {len(rows)};\n"
        + arr("kX", "int16_t", xs) + arr("kY", "int16_t", ys) + arr("kT", "uint16_t", ts)
        + f"const size_t kPointCount = {len(xs)};\n}}  // namespace cursory::data\n")
    return HEADER_H, src

HEADER_COMMENT = (
    "// Copyright 2026 The Camoucrome Authors. Derived from cursory 2.1.0\n"
    "// (Vinyzu), LGPL-3.0-or-later; see NOTICE. GENERATED by\n"
    "// scripts/gen_cursory_table.py -- do not edit.\n\n")
HEADER_H = (
    HEADER_COMMENT
    + "#ifndef COMPONENTS_CAMOUCFG_LGPL_CURSORY_DATA_H_\n#define COMPONENTS_CAMOUCFG_LGPL_CURSORY_DATA_H_\n\n"
    "#include <cstddef>\n#include <cstdint>\n\nnamespace cursory::data {\n"
    "struct Recording { uint32_t first_point; uint16_t point_count; float length; };\n"
    "extern const Recording kRecordings[];\nextern const size_t kRecordingCount;\n"
    "extern const int16_t kX[];\nextern const int16_t kY[];\nextern const uint16_t kT[];\n"
    "extern const size_t kPointCount;\n}  // namespace cursory::data\n\n"
    "#endif  // COMPONENTS_CAMOUCFG_LGPL_CURSORY_DATA_H_\n")

def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out-dir", default=LGPL)
    a = ap.parse_args(argv)
    sha = hashlib.sha256(open(SNAPSHOT, "rb").read()).hexdigest()
    if sha != PINNED_SHA256:
        print(f"snapshot sha256 {sha} != pinned {PINNED_SHA256}", file=sys.stderr); return 1
    h, c = render(load(SNAPSHOT))
    paths = {os.path.join(a.out_dir, "cursory_data.h"): h, os.path.join(a.out_dir, "cursory_data.cc"): c}
    if a.check:
        for p, want in paths.items():
            if not os.path.exists(p) or open(p).read() != want:
                print(f"stale: {p}", file=sys.stderr); return 1
        return 0
    for p, text in paths.items():
        open(p, "w").write(text)
    return 0

if __name__ == "__main__":
    sys.exit(main())
