#!/usr/bin/env python3
"""Generates the SP2d click tables from the oracle's summary.

    scripts/gen_click_tables.py --baseline baselines/human-click-2026-10 --provisional
    scripts/gen_click_tables.py --check   print `stale: <path>` per drifted file, exit 1

Outputs, all committed (so --check is the drift gate, as with keys.h):
  additions/camoucfg/human_input_tables.h  the hold and dwell knots the browser samples
  client/python/camoucrome/_click_tables.py
  client/node/click_tables.js
  client/go/click_tables.go
  settings/launcher.json                   its humanClick block; every other key is kept

The tables come from capture_click_oracle.summarize over the mac arm files
(`mac-s*.json`). Two floors keep a thin capture from looking like data:
strict mode needs 2 sessions and 200 clicks, and render refuses a 5th
percentile below 25 ms, where H0's 15 ms threshold could not separate the
spoof from the raw value.

`--root` redirects the outputs only (the tests use it); the inputs are the
baseline directory it is given and this repository's settings/launcher.json.
"""
import argparse
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import capture_click_oracle as oracle

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADER = "GENERATED by scripts/gen_click_tables.py from baselines/human-click-2026-10 — do not edit"
OUTPUTS = {
    "cpp": "additions/camoucfg/human_input_tables.h",
    "py": "client/python/camoucrome/_click_tables.py",
    "js": "client/node/click_tables.js",
    "go": "client/go/click_tables.go",
}
LAUNCHER = "settings/launcher.json"
GEOMETRY = "settings/human_click_geometry.js"

# The client limits: the same in all three clients, so one of them cannot admit
# a burst or an inset another refuses.
INNER_FRACTION = 0.8
MIN_SIDE_PX = 4
MAX_REDRAWS = 8
MAX_NOTCHES = 60
NO_PROGRESS_BURSTS = 2
TRIAL_TIMEOUT_MS = 2000
# The browser's clamps on a sampled hold and dwell.
MAX_HOLD_MS = 400
MAX_DWELL_MS = 600


def load(baseline, provisional):
    """The oracle summary over the baseline's mac arm files. Unless provisional,
    exits while the capture is too thin to describe a person."""
    arms = {}
    for p in sorted(pathlib.Path(baseline).glob("mac-s*.json")):
        arms[p.stem] = json.loads(p.read_text())
    n_clicks = sum(len(a["clicks"]) for a in arms.values())
    if not provisional and (len(arms) < 2 or n_clicks < 200):
        sys.exit(f"{baseline}: need ≥ 2 sessions and ≥ 200 clicks, have {len(arms)} "
                 f"sessions and {n_clicks} clicks")
    return oracle.summarize(arms)


def render(summary):
    """The four file texts and the launcher block."""
    scroll = summary["scroll"]
    if scroll is None:
        sys.exit("no scrolls in the baseline: landing, burst and pause need the scroll arm")
    tables = {"hold_ms": summary["hold_ms"], "dwell_ms": summary["dwell_ms"],
              "landing": scroll["landing"], "burst": scroll["burst"], "pause": scroll["pause"]}
    for name, knots in tables.items():
        if len(knots) != 21:
            sys.exit(f"{name}: expected 21 knots, got {len(knots)}")
    if summary["hold_ms"][1] < 25 or summary["dwell_ms"][1] < 25:
        sys.exit("p5 below 25 ms: H0's 15 ms threshold would not separate")

    off = summary["offset"]
    model = {axis: {"a": float(off[axis]["a"]), "b": float(off[axis]["b"])}
             for axis in ("along", "across")}
    block = {
        "offset": model,
        "landing": [float(v) for v in tables["landing"]],
        "burst": [float(v) for v in tables["burst"]],
        "pause": [float(v) for v in tables["pause"]],
        "innerFraction": INNER_FRACTION,
        "minSidePx": MIN_SIDE_PX,
        "maxRedraws": MAX_REDRAWS,
        "maxNotches": MAX_NOTCHES,
        "noProgressBursts": NO_PROGRESS_BURSTS,
        "trialTimeoutMs": TRIAL_TIMEOUT_MS,
        "go": "no human_click flag (B); HumanClick only",
        "outOfScope": [
            "touch taps: A and B act on mouse presses only",
            "double clicks and drags (B passes them through unchanged)",
            "elements in a nested scroller, or off the document scroller (stock click)",
            "clicks that pass position, force or trial themselves (stock click)",
        ],
    }
    geometry = (ROOT / GEOMETRY).read_text()
    return {"cpp": _cpp(tables), "py": _py(tables, model, geometry),
            "js": _js(tables, model, geometry), "go": _go(tables, model, geometry),
            "launcher_block": block}


def _cpp(tables):
    return "".join([
        f"// {HEADER}\n\n",
        "#ifndef COMPONENTS_CAMOUCFG_HUMAN_INPUT_TABLES_H_\n",
        "#define COMPONENTS_CAMOUCFG_HUMAN_INPUT_TABLES_H_\n\n",
        "namespace camoucfg {\n\n",
        "// Hold (press to release) and dwell (last move to press), in ms, as knots\n",
        "// at p0, p5, ... p95, p99 of the oracle's mac clicks. HumanInput samples\n",
        "// them with SampleKnots.\n",
        f"inline constexpr double kHoldMsKnots[21] = {{{_g(tables['hold_ms'])}}};\n",
        f"inline constexpr double kDwellMsKnots[21] = {{{_g(tables['dwell_ms'])}}};\n\n",
        "// Clamps. A sampled value above these is a hit-test that did not resolve\n",
        "// in the oracle's window, not a click.\n",
        f"inline constexpr double kMaxHoldMs = {MAX_HOLD_MS};\n",
        f"inline constexpr double kMaxDwellMs = {MAX_DWELL_MS};\n\n",
        "}  // namespace camoucfg\n\n",
        "#endif  // COMPONENTS_CAMOUCFG_HUMAN_INPUT_TABLES_H_\n",
    ])


def _py(tables, model, geometry):
    return "".join([
        f"# {HEADER}\n",
        '"""SP2d click tables: the browser\'s hold and dwell knots, then the\n'
        "client's offset model, scroll bursts, limits and the geometry function\n"
        'every client evaluates in the isolated world."""\n\n',
        f"HOLD_MS = {_repr_list(tables['hold_ms'])}\n",
        f"DWELL_MS = {_repr_list(tables['dwell_ms'])}\n\n",
        f'OFFSET = {{"along": {{"a": {model["along"]["a"]!r}, "b": {model["along"]["b"]!r}}},\n'
        f'          "across": {{"a": {model["across"]["a"]!r}, "b": {model["across"]["b"]!r}}}}}\n\n',
        f"LANDING = {_repr_list(tables['landing'])}\n",
        f"BURST = {_repr_list(tables['burst'])}\n",
        f"PAUSE = {_repr_list(tables['pause'])}\n\n",
        f"INNER_FRACTION = {INNER_FRACTION!r}\n",
        f"MIN_SIDE_PX = {MIN_SIDE_PX}\n",
        f"MAX_REDRAWS = {MAX_REDRAWS}\n",
        f"MAX_NOTCHES = {MAX_NOTCHES}\n",
        f"NO_PROGRESS_BURSTS = {NO_PROGRESS_BURSTS}\n",
        f"TRIAL_TIMEOUT_MS = {TRIAL_TIMEOUT_MS}\n\n",
        f"GEOMETRY_JS = {geometry!r}\n",
    ])


def _js(tables, model, geometry):
    return "".join([
        f"// {HEADER}\n",
        "'use strict';\n\n",
        f"const holdMs = {_js_list(tables['hold_ms'])};\n",
        f"const dwellMs = {_js_list(tables['dwell_ms'])};\n\n",
        f"const offset = {{along: {{a: {model['along']['a']!r}, b: {model['along']['b']!r}}},\n"
        f"  across: {{a: {model['across']['a']!r}, b: {model['across']['b']!r}}}}};\n\n",
        f"const landing = {_js_list(tables['landing'])};\n",
        f"const burst = {_js_list(tables['burst'])};\n",
        f"const pause = {_js_list(tables['pause'])};\n\n",
        f"const innerFraction = {INNER_FRACTION!r};\n",
        f"const minSidePx = {MIN_SIDE_PX};\n",
        f"const maxRedraws = {MAX_REDRAWS};\n",
        f"const maxNotches = {MAX_NOTCHES};\n",
        f"const noProgressBursts = {NO_PROGRESS_BURSTS};\n",
        f"const trialTimeoutMs = {TRIAL_TIMEOUT_MS};\n\n",
        f"// The shared geometry function, verbatim as settings/{GEOMETRY.rsplit('/', 1)[1]}.\n",
        f"const geometryJS = {json.dumps(geometry)};\n\n",
        "module.exports = {holdMs, dwellMs, offset, landing, burst, pause, innerFraction,\n"
        "  minSidePx, maxRedraws, maxNotches, noProgressBursts, trialTimeoutMs, geometryJS};\n",
    ])


def _go(tables, model, geometry):
    return "".join([
        f"// {HEADER}\n",
        "package camoucrome\n\n",
        f"var clickLanding = [21]float64{{{_g(tables['landing'])}}}\n",
        f"var clickBurst = [21]float64{{{_g(tables['burst'])}}}\n",
        f"var clickPause = [21]float64{{{_g(tables['pause'])}}}\n\n",
        f"var clickOffset = offsetModel{{Along: axisModel{{A: {model['along']['a']:.17g}, "
        f"B: {model['along']['b']:.17g}}}, Across: axisModel{{A: {model['across']['a']:.17g}, "
        f"B: {model['across']['b']:.17g}}}}}\n\n",
        "const (\n",
        f"\tclickInnerFraction = {INNER_FRACTION!r}\n",
        f"\tclickMinSidePx = {MIN_SIDE_PX}\n",
        f"\tclickMaxRedraws = {MAX_REDRAWS}\n",
        f"\tclickMaxNotches = {MAX_NOTCHES}\n",
        f"\tclickNoProgressBursts = {NO_PROGRESS_BURSTS}\n",
        f"\tclickTrialTimeoutMs = {TRIAL_TIMEOUT_MS}\n",
        ")\n\n",
        f"const geometryJS = `{geometry}`\n",
    ])


def _g(values):
    """%.17g: a double round-trips through the literal (C++ and Go)."""
    return ", ".join("%.17g" % v for v in values)


def _repr_list(values):
    """repr: a Python float round-trips through its shortest literal."""
    return "[%s]" % ", ".join(repr(float(v)) for v in values)


def _js_list(values):
    """The shortest literal that round-trips, which is what String gives."""
    return "[%s]" % ", ".join(repr(float(v)) for v in values)


def launcher_text(block):
    """settings/launcher.json with its humanClick block replaced. The file's key
    order and its json.dump(indent=1) style are kept; the block is appended."""
    data = json.loads((ROOT / LAUNCHER).read_text())
    data["humanClick"] = block
    return json.dumps(data, indent=1) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--baseline", default=str(ROOT / "baselines" / "human-click-2026-10"),
                    help="the oracle's arm directory (mac-s*.json)")
    ap.add_argument("--provisional", action="store_true",
                    help="accept a thin capture: fewer than 2 sessions or 200 clicks")
    ap.add_argument("--check", action="store_true",
                    help="compare instead of writing; exit 1 on a stale output")
    ap.add_argument("--root", default=str(ROOT), help="write the outputs under this directory")
    a = ap.parse_args(argv)

    out = render(load(a.baseline, a.provisional))
    files = {rel: out[kind] for kind, rel in OUTPUTS.items()}
    files[LAUNCHER] = launcher_text(out["launcher_block"])

    root = pathlib.Path(a.root)
    stale = []
    for rel, text in files.items():
        path = root / rel
        if a.check:
            if not path.exists() or path.read_text() != text:
                stale.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {rel}")
    if stale:
        for rel in stale:
            print(f"stale: {rel}")
        sys.exit(1)


if __name__ == "__main__":
    main()
