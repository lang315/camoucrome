#!/usr/bin/env python3
"""Generates additions/camoucfg/observe_blowfish_init.cc: Blowfish's P and S
tables, which are the hex digits of pi.

    scripts/gen_blowfish_init.py          rewrite the file
    scripts/gen_blowfish_init.py --check  exit 1 if the file differs
"""
import os
import sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                   "additions", "camoucfg", "observe_blowfish_init.cc")


def arccot(x, unity):
    total = power = unity // x
    n, sign, x2 = 3, -1, x * x
    while power:
        power //= x2
        total += sign * (power // n)
        sign, n = -sign, n + 2
    return total


def pi_words(count=1042, guard=16):
    unity = 1 << (4 * (count * 8 + guard))
    pi = 4 * (4 * arccot(5, unity) - arccot(239, unity))
    digits = format(pi >> (4 * guard), "x")
    assert digits[0] == "3"
    return [int(digits[1 + 8 * i: 9 + 8 * i], 16) for i in range(count)]


def _rows(words):
    lines = []
    for i in range(0, len(words), 6):
        lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 6]) + ",")
    return "\n".join(lines)


def render():
    w = pi_words()
    p, s = w[:18], w[18:]
    out = """// Copyright 2026 The Camoucrome Authors
// Use of this source code is governed by a BSD-style license that can be
// found in the LICENSE file.

// Generated by scripts/gen_blowfish_init.py from the hex digits of pi. Do not edit.

#include "components/camoucfg/observe_blowfish.h"

namespace camoucfg::observe {

const uint32_t kBlowfishInitP[18] = {
%s
};

const uint32_t kBlowfishInitS[4][256] = {
""" % _rows(p)
    for b in range(4):
        out += "    {\n%s\n    },\n" % _rows(s[b * 256:(b + 1) * 256]).replace("\n    ", "\n      ").replace("    0x", "      0x", 1)
    out += "};\n\n}  // namespace camoucfg::observe\n"
    return out


def main():
    text = render()
    if "--check" in sys.argv:
        try:
            same = open(OUT).read() == text
        except FileNotFoundError:
            same = False
        return 0 if same else 1
    with open(OUT, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
