#!/usr/bin/env python3
"""Writes settings/human_click_vectors.json and the C++ unittest include from
client/python/camoucrome/human_math.py (the reference). --check: exit 1 if stale."""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "client" / "python"))
from camoucrome import human_math as m  # noqa: E402

KNOTS = [0, 1, 3, 6, 10, 15, 21, 28, 36, 45, 55, 66, 78, 91, 105, 120, 136, 153, 171, 190, 210]
MODEL = {"along": {"a": 2.0, "b": 0.06}, "across": {"a": 1.5, "b": 0.04}}
GEO = dict(x=100.0, y=200.0, w=120.0, h=40.0, n=1, bl=2.0, bt=2.0, t=False, vw=1280.0, vh=720.0, scroller="document")


def case_click(geo, last, rand, scale=1.0):
    it = iter(rand)
    pos = m.click_position(geo, last, MODEL, scale, lambda: next(it))
    return {"geo": geo, "last": last, "model": MODEL, "scale": scale, "rand": rand,
            "position": list(pos) if pos else None}


def case_burst(geo, landing, rand):
    it = iter(rand)
    out = m.next_burst(geo, landing, KNOTS, [100.0 + 10 * i for i in range(21)], lambda: next(it))
    return {"geo": geo, "landing": landing, "burst": KNOTS, "pause": [100.0 + 10 * i for i in range(21)],
            "rand": rand, "out": list(out) if out else None}


def build():
    v = {
        "splitmix64": [[f"{x:016x}", f"{m.splitmix64(x):016x}"] for x in (0, 1, 0xFFFFFFFF, 0xDEADBEEFCAFEBABE)],
        "profile_scale": [{"seed": s, "salt": salt, "scale": m.profile_scale(s, salt)}
                          for s in (None, 1, 2, 12345, 0xFFFFFFFF) for salt in ("hold", "dwell", "offset")],
        "sample_knots": [{"knots": KNOTS, "u": u, "value": m.sample_knots(KNOTS, u)} for u in (0.0, 0.025, 0.5, 0.9, 0.999)],
        "edge_entry": [{"w": 1280.0, "h": 720.0, "u": [ue, 0.37, 0.5], "point": list(m.edge_entry(1280.0, 720.0, ue, 0.37, 0.5))}
                       for ue in (0.1, 0.3, 0.6, 0.9)] + [{"w": 1.0, "h": 1.0, "u": [0.5, 0.5, 0.5], "point": [0.0, 0.0]}],
        "click_position": [
            case_click(GEO, None, [0.3, 0.1]),
            case_click(GEO, [0.0, 0.0], [0.6, 0.8]),
            case_click({**GEO, "bl": 0.0, "bt": 0.0}, [400.0, 500.0], [0.2, 0.45]),
            case_click(GEO, None, [0.9999999999] * 2 + [0.3, 0.1]),   # radius ~6.8 SD: rejected, then kept
            case_click(GEO, None, [0.9999999999] * 16),               # all 8 redraws rejected -> None
            case_click({**GEO, "w": 3.0}, None, []),
            case_click({**GEO, "t": True}, None, []),
            case_click({**GEO, "n": 2}, None, []),
        ],
        "next_burst": [
            case_burst({**GEO, "y": 100.0}, 0.3, [0.5, 0.5]),     # visible, but 116 px above L=216: a burst
            case_burst({**GEO, "y": 3000.0}, 0.3, [0.5, 0.5]),
            case_burst({**GEO, "y": -900.0}, 0.3, [0.2, 0.7]),
            case_burst({**GEO, "y": 800.0, "h": 2000.0}, 0.2, [0.9, 0.1]),  # taller than vh: L=0
            case_burst({**GEO, "y": 99000.0}, 0.3, [1.0, 0.5]),   # clamped at 60
            case_burst({**GEO, "y": 1440.0}, 2.0, [0.5, 0.5]),    # landing 1440 clamps to L=680, delta=760
            case_burst({**GEO, "y": 230.0}, 0.3, [0.5, 0.5]),     # visible, 14 px from L=216 -> None
            case_burst({**GEO, "y": 265.0}, 0.3, [0.5, 0.5]),     # visible, 49 px from L -> None
            case_burst({**GEO, "y": 267.0}, 0.3, [0.5, 0.5]),     # visible, 51 px from L: a burst
            case_burst({**GEO, "y": 690.0}, 0.95, [0.5, 0.5]),    # L clamps to 680; 10 px below it, not fully visible
            case_burst({**GEO, "y": 670.0}, 0.95, [0.5, 0.5]),    # visible, 10 px above the clamped L -> None
            case_burst({**GEO, "y": 20.0, "h": 2000.0}, 0.3, [0.5, 0.5]),  # taller than vh: L=0, visible
        ],
    }
    salts = {"hold": 0, "dwell": 1, "offset": 2}
    inc = ["// GENERATED by scripts/gen_click_vectors.py -- do not edit", "namespace camoucfg {", "namespace {"]
    inc.append("constexpr uint64_t kVecSplitmix64[][2] = {" + ", ".join(f"{{0x{a}ull, 0x{b}ull}}" for a, b in v["splitmix64"]) + "};")
    inc.append("struct VecScale { uint32_t seed; bool has_seed; int salt_index; double scale; };")
    inc.append("constexpr VecScale kVecProfileScale[] = {" + ", ".join(
        f"{{{c['seed'] or 0}u, {'true' if c['seed'] is not None else 'false'}, {salts[c['salt']]}, {c['scale']!r}}}"
        for c in v["profile_scale"]) + "};")
    inc.append("struct VecKnots { double knots[21]; double u; double value; };")
    inc.append("constexpr VecKnots kVecSampleKnots[] = {" + ", ".join(
        "{{" + ", ".join(repr(float(k)) for k in c["knots"]) + f"}}, {c['u']!r}, {c['value']!r}}}" for c in v["sample_knots"]) + "};")
    inc.append("struct VecEdge { double w; double h; double u[3]; double x; double y; };")
    inc.append("constexpr VecEdge kVecEdgeEntry[] = {" + ", ".join(
        f"{{{c['w']!r}, {c['h']!r}, {{{', '.join(repr(x) for x in c['u'])}}}, {c['point'][0]!r}, {c['point'][1]!r}}}"
        for c in v["edge_entry"]) + "};")
    inc += ["}  // namespace", "}  // namespace camoucfg", ""]
    return {ROOT / "settings" / "human_click_vectors.json": json.dumps(v, indent=1) + "\n",
            ROOT / "additions" / "camoucfg" / "human_input_vectors_unittest.inc": "\n".join(inc)}


def main():
    stale = 0
    for path, text in build().items():
        if "--check" in sys.argv:
            if not path.exists() or path.read_text() != text:
                print(f"stale: {path.relative_to(ROOT)}")
                stale = 1
        else:
            path.write_text(text)
    return stale


if __name__ == "__main__":
    sys.exit(main())
