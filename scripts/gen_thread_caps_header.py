#!/usr/bin/env python3
"""Generates additions/camoucfg/igpu_thread_caps.h from
settings/webgl/intel-gen9-thread-caps.json and settings/webgl/igpu-thread-caps.json.

    scripts/gen_thread_caps_header.py          rewrite the header
    scripts/gen_thread_caps_header.py --check  exit 1 if the header is stale

One row per (vendor, device id): the smallest and the largest thread count any
CPU shipping that iGPU has. Rows without a sourced max_threads are left out: no
cap means no constraint. A row without a sourced min_threads has min 0: no floor.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
GEN9 = ROOT / "settings" / "webgl" / "intel-gen9-thread-caps.json"
IGPU = ROOT / "settings" / "webgl" / "igpu-thread-caps.json"
HEADER = ROOT / "additions" / "camoucfg" / "igpu_thread_caps.h"

TEMPLATE = """\
// Copyright 2026 The Camoucrome Authors
// Use of this source code is governed by a BSD-style license that can be
// found in the LICENSE file.

#ifndef COMPONENTS_CAMOUCFG_IGPU_THREAD_CAPS_H_
#define COMPONENTS_CAMOUCFG_IGPU_THREAD_CAPS_H_

#include <array>
#include <cstdint>
#include <optional>

// GENERATED by scripts/gen_thread_caps_header.py from settings/webgl/intel-gen9-thread-caps.json and settings/webgl/igpu-thread-caps.json -- do not edit
//
// The fewest and the most hardware threads any CPU (or APU) shipping each iGPU
// (vendor + PCI device id) lists. Sorted by vendor, then device id. A pair
// absent here has no sourced cap and constrains nothing; min_threads 0 means
// no sourced floor.

namespace camoucfg {

enum class IgpuVendor { kAmd, kIntel };  // the table sort order

struct IgpuThreadRange {
  IgpuVendor vendor;
  uint32_t device_id;
  uint32_t min_threads;
  uint32_t max_threads;
};

inline constexpr std::array<IgpuThreadRange, %(n)d> kIgpuThreadRanges = {{
%(rows)s
}};

constexpr const IgpuThreadRange* IgpuThreadRangeFor(IgpuVendor vendor,
                                                    uint32_t device_id) {
  for (const IgpuThreadRange& r : kIgpuThreadRanges) {
    if (r.vendor == vendor && r.device_id == device_id) {
      return &r;
    }
  }
  return nullptr;
}

}  // namespace camoucfg

#endif  // COMPONENTS_CAMOUCFG_IGPU_THREAD_CAPS_H_
"""

ENUM = {"Intel": "kIntel", "AMD": "kAmd"}


def rows_of(gen9, igpu):
    """[(vendor, id, min, max)] sorted by vendor name, then id; the Gen9 file is all Intel."""
    out = {}
    for vendor_of, rows in ((lambda r: "Intel", gen9), (lambda r: r["vendor"], igpu)):
        for r in rows:
            if r["max_threads"] is None:
                continue
            key = (vendor_of(r), int(r["device_id"], 16))
            assert key not in out, f"{key} is in both files"
            out[key] = (r.get("min_threads") or 0, r["max_threads"])
    return sorted((ENUM[v], i, lo, hi) for (v, i), (lo, hi) in out.items())


def render(gen9, igpu):
    rows = rows_of(gen9, igpu)
    body = "\n".join(f"    {{IgpuVendor::{v}, 0x{i:04X}, {lo}, {hi}}}," for v, i, lo, hi in rows)
    return TEMPLATE % {"n": len(rows), "rows": body}


def rendered():
    return render(json.loads(GEN9.read_text())["rows"], json.loads(IGPU.read_text())["rows"])


def main(argv):
    out = rendered()
    if "--check" in argv:
        if not HEADER.exists() or HEADER.read_text() != out:
            print("FAIL  igpu_thread_caps.h is stale; run scripts/gen_thread_caps_header.py")
            return 1
        print("PASS  igpu_thread_caps.h matches intel-gen9-thread-caps.json and igpu-thread-caps.json")
        return 0
    HEADER.write_text(out)
    print(f"wrote {HEADER.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
