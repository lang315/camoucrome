#!/usr/bin/env python3
"""Generates additions/camoucfg/gen9_thread_caps.h from
settings/webgl/intel-gen9-thread-caps.json.

    scripts/gen_thread_caps_header.py          rewrite the header
    scripts/gen_thread_caps_header.py --check  exit 1 if the header is stale

Rows without a sourced max_threads are left out: no cap means no constraint.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "settings" / "webgl" / "intel-gen9-thread-caps.json"
HEADER = ROOT / "additions" / "camoucfg" / "gen9_thread_caps.h"

TEMPLATE = """\
// Copyright 2026 The Camoucrome Authors
// Use of this source code is governed by a BSD-style license that can be
// found in the LICENSE file.

#ifndef COMPONENTS_CAMOUCFG_GEN9_THREAD_CAPS_H_
#define COMPONENTS_CAMOUCFG_GEN9_THREAD_CAPS_H_

#include <array>
#include <cstdint>
#include <optional>

// GENERATED by scripts/gen_thread_caps_header.py from settings/webgl/intel-gen9-thread-caps.json -- do not edit
//
// The most hardware threads any CPU shipping each Intel Gen9 iGPU (PCI device
// id) lists on Intel ARK. Sorted by device id. A device id absent here has no
// sourced cap and constrains nothing.

namespace camoucfg {

struct Gen9ThreadCap {
  uint32_t device_id;
  uint32_t max_threads;
};

inline constexpr std::array<Gen9ThreadCap, %(n)d> kGen9ThreadCaps = {{
%(rows)s
}};

constexpr std::optional<uint32_t> Gen9ThreadCapFor(uint32_t device_id) {
  for (const Gen9ThreadCap& cap : kGen9ThreadCaps) {
    if (cap.device_id == device_id) {
      return cap.max_threads;
    }
  }
  return std::nullopt;
}

}  // namespace camoucfg

#endif  // COMPONENTS_CAMOUCFG_GEN9_THREAD_CAPS_H_
"""


def render(rows):
    sourced = sorted((int(r["device_id"], 16), r["max_threads"])
                     for r in rows if r["max_threads"] is not None)
    body = "\n".join(f"    {{0x{i:04X}, {t}}}," for i, t in sourced)
    return TEMPLATE % {"n": len(sourced), "rows": body}


def main(argv):
    rendered = render(json.loads(SOURCE.read_text())["rows"])
    if "--check" in argv:
        if not HEADER.exists() or HEADER.read_text() != rendered:
            print("FAIL  gen9_thread_caps.h is stale; run scripts/gen_thread_caps_header.py")
            return 1
        print("PASS  gen9_thread_caps.h matches intel-gen9-thread-caps.json")
        return 0
    HEADER.write_text(rendered)
    print(f"wrote {HEADER.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
