"""gen_thread_caps_header.py and the C++ side that consumes its header."""
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import gen_thread_caps_header as gen  # noqa: E402

CAMOUCFG = ROOT / "additions" / "camoucfg"
HEADER = CAMOUCFG / "igpu_thread_caps.h"
GEN9 = json.loads(gen.GEN9.read_text())["rows"]
IGPU = json.loads(gen.IGPU.read_text())["rows"]
# (vendor, id) -> (min, max) of every sourced row of both files
EXPECTED = {("Intel", int(r["device_id"], 16)): (r.get("min_threads") or 0, r["max_threads"])
            for r in GEN9 if r["max_threads"] is not None}
EXPECTED.update({(r["vendor"], int(r["device_id"], 16)): (r.get("min_threads") or 0, r["max_threads"])
                 for r in IGPU if r["max_threads"] is not None})
VENDOR = {"kIntel": "Intel", "kAmd": "AMD"}


def committed_table():
    return [(VENDOR[v], int(i, 16), int(lo), int(hi)) for v, i, lo, hi in
            re.findall(r"\{IgpuVendor::(\w+), (0x[0-9A-Fa-f]+), (\d+), (\d+)\}", HEADER.read_text())]


def test_check_passes():
    r = subprocess.run([sys.executable, str(ROOT / "scripts/gen_thread_caps_header.py"), "--check"])
    assert r.returncode == 0


def test_rendered_matches_committed_file():
    assert gen.rendered() == HEADER.read_text()


def test_banner_present():
    assert ("// GENERATED by scripts/gen_thread_caps_header.py from settings/webgl/intel-gen9-thread-caps.json "
            "and settings/webgl/igpu-thread-caps.json -- do not edit") in HEADER.read_text()


def test_sorted_and_unique():
    keys = [(gen.ENUM[v], i) for v, i, _, _ in committed_table()]
    assert keys == sorted(set(keys))


def test_no_unsourced_row():
    unsourced = {("Intel", int(r["device_id"], 16)) for r in GEN9 if r["max_threads"] is None}
    unsourced |= {(r["vendor"], int(r["device_id"], 16)) for r in IGPU if r["max_threads"] is None}
    assert unsourced and not unsourced & {(v, i) for v, i, _, _ in committed_table()}


def test_table_equals_sourced_rows_with_floors():
    assert len(committed_table()) == len(EXPECTED)
    assert {(v, i): (lo, hi) for v, i, lo, hi in committed_table()} == EXPECTED
    assert f"std::array<IgpuThreadRange, {len(EXPECTED)}>" in HEADER.read_text()
    assert any(lo > 0 for _, _, lo, _ in committed_table())


def test_a_gen9_floor_reaches_the_header():
    uhd620 = next(r for r in GEN9 if r["device_id"] == "0x3EA0")
    assert ("Intel", 0x3EA0, uhd620["min_threads"], uhd620["max_threads"]) in committed_table()


def test_registry_entry():
    inv = json.loads((ROOT / "settings/invariants.json").read_text())["invariants"]
    assert len(inv) == 16
    e = next(e for e in inv if e["id"] == "gpu-renderer-fits-threads")
    assert e["keys"] == ["webGl:renderer", "navigator.hardwareConcurrency"]
    assert e["relation"] == "renderer-fits-threads" and e["policy"] == "report"


def test_cpp_array_sizes():
    inv_h = (CAMOUCFG / "invariants.h").read_text()
    ut = (CAMOUCFG / "coherence_validator_unittest.cc").read_text()
    assert re.search(r"std::array<Invariant, 16> kAllInvariants", inv_h)
    assert re.search(r"std::array<Mutation, 17> kMutations", ut)
    assert '"gpu-renderer-fits-threads"' in inv_h and '"gpu-renderer-fits-threads"' in ut
