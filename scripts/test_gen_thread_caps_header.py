"""gen_thread_caps_header.py and the C++ side that consumes its header."""
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import gen_thread_caps_header as gen  # noqa: E402

CAMOUCFG = ROOT / "additions" / "camoucfg"
HEADER = CAMOUCFG / "gen9_thread_caps.h"
ROWS = json.loads(gen.SOURCE.read_text())["rows"]
SOURCED = [r for r in ROWS if r["max_threads"] is not None]


def committed_table():
    return [(int(a, 16), int(b)) for a, b in
            re.findall(r"\{(0x[0-9A-Fa-f]+), (\d+)\}", HEADER.read_text())]


def test_check_passes():
    r = subprocess.run([sys.executable, str(ROOT / "scripts/gen_thread_caps_header.py"), "--check"])
    assert r.returncode == 0


def test_rendered_matches_committed_file():
    assert gen.render(ROWS) == HEADER.read_text()


def test_banner_present():
    assert ("// GENERATED by scripts/gen_thread_caps_header.py from "
            "settings/webgl/intel-gen9-thread-caps.json -- do not edit") in HEADER.read_text()


def test_sorted_and_unique():
    ids = [i for i, _ in committed_table()]
    assert ids == sorted(set(ids))


def test_no_unsourced_row():
    unsourced = {int(r["device_id"], 16) for r in ROWS if r["max_threads"] is None}
    assert unsourced and not unsourced & {i for i, _ in committed_table()}


def test_table_equals_sourced_rows():
    assert len(committed_table()) == len(SOURCED)
    assert dict(committed_table()) == {int(r["device_id"], 16): r["max_threads"] for r in SOURCED}
    assert f"std::array<Gen9ThreadCap, {len(SOURCED)}>" in HEADER.read_text()


def test_registry_entry():
    inv = json.loads((ROOT / "settings/invariants.json").read_text())["invariants"]
    assert len(inv) == 16
    e = next(e for e in inv if e["id"] == "gpu-renderer-fits-threads")
    assert e["keys"] == ["webGl:renderer", "navigator.hardwareConcurrency"]
    assert e["relation"] == "renderer-fits-threads" and e["policy"] == "report"


def test_cpp_array_sizes():
    inv_h = (CAMOUCFG / "invariants.h").read_text()
    ut = (CAMOUCFG / "coherence_validator_unittest.cc").read_text()
    assert re.search(r"std::array<Invariant, 16> kAllInvariants", inv_h)
    assert re.search(r"std::array<Mutation, 16> kMutations", ut)
    assert '"gpu-renderer-fits-threads"' in inv_h and '"gpu-renderer-fits-threads"' in ut
